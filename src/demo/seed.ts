/**
 * A due time, expressed as a wall-clock hour on a future day.
 *
 * The demo has to read "Return tomorrow by 21:00" whenever it is opened, so
 * the fixture is relative to now rather than a date that quietly becomes
 * last Tuesday.
 */
function atHour(daysFromNow: number, hour: number, minute = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + daysFromNow);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

