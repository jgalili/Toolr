export const FLORENTIN = { latitude: 32.0553, longitude: 34.7688 };

/** Offset a point by metres — used to place seed tools believably around the centre. */
function offset(metresNorth: number, metresEast: number) {
  return {
    latitude: FLORENTIN.latitude + metresNorth / 111_320,
    longitude:
      FLORENTIN.longitude + metresEast / (111_320 * Math.cos((FLORENTIN.latitude * Math.PI) / 180)),
  };
}

/**
 * The same pickup windows on every day of the week.
 *
 * Real listings vary by day; a demo that only opens on Tuesdays shows an empty
 * "Available today" panel six days out of seven, which reads as a bug.
 */
function everyDay(slots: [string, string][]): PickupWindow[] {
  return [0, 1, 2, 3, 4, 5, 6].flatMap((weekday) =>
    slots.map(([startTime, endTime]) => ({ weekday, startTime, endTime })),
  );
}

